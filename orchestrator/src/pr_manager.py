"""GitHub Pull Request creation, updating, and auto-merge."""
from __future__ import annotations

from github import Github

from retry import retry_with_backoff

import logger as log


def _enable_auto_merge(pr) -> None:
    """Enable auto-merge (squash) on a PR via the GraphQL API.

    Requires the repo to have "Allow auto-merge" enabled in settings
    and branch protection rules with required reviews/checks.
    Silently skips if auto-merge is not available.
    """
    try:
        pr.enable_automerge(merge_method="SQUASH")
    except Exception:
        # PyGithub may not support enable_automerge; fall back to GraphQL
        try:
            requester = pr._requester
            mutation = """
                mutation($prId: ID!) {
                    enablePullRequestAutoMerge(input: {pullRequestId: $prId, mergeMethod: SQUASH}) {
                        clientMutationId
                    }
                }
            """
            requester.requestJsonAndCheck(
                "POST", "/graphql",
                input={"query": mutation, "variables": {"prId": pr.node_id}},
            )
        except Exception as exc:
            log.info("Could not enable auto-merge (repo may not support it)", error=str(exc))


def build_pr_body(issue_number: int, issue_title: str) -> str:
    """Build the PR description body.

    The body always contains the issue number, issue title, and a non-empty
    summary section.
    """
    return (
        f"Closes #{issue_number}\n\n"
        f"## Summary\n\n"
        f"This PR implements the changes requested in issue #{issue_number}: "
        f"_{issue_title}_.\n\n"
        f"Generated by Devless."
    )


def build_commit_message(issue_number: int, issue_title: str) -> str:
    """Build a commit message referencing the issue number and title.

    Both the issue number and issue title are guaranteed to appear as
    substrings in the returned message.
    """
    return f"[Issue #{issue_number}] {issue_title}"


def create_or_update_pr(
    repo_full_name: str,
    issue_number: int,
    issue_title: str,
    branch: str,
    token: str,
) -> str:
    """Create or update a PR for the issue branch. Returns the PR URL."""

    def _do_create_or_update() -> str:
        gh = Github(token)
        repo = gh.get_repo(repo_full_name)
        default_branch = repo.default_branch

        pr_title = f"[Issue #{issue_number}] {issue_title}"
        pr_body = build_pr_body(issue_number, issue_title)

        # Check for an existing open PR on this branch
        open_prs = list(repo.get_pulls(state="open", head=f"{repo.owner.login}:{branch}"))
        if open_prs:
            pr = open_prs[0]
            pr.edit(title=pr_title, body=pr_body)
            _enable_auto_merge(pr)
            return pr.html_url

        pr = repo.create_pull(
            title=pr_title,
            body=pr_body,
            head=branch,
            base=default_branch,
        )
        _enable_auto_merge(pr)
        return pr.html_url

    return retry_with_backoff(_do_create_or_update)
